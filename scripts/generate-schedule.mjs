import { existsSync } from "node:fs";
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { basename, dirname, extname } from "node:path";

import { format, resolveConfig } from "prettier";

import { parseScheduleSheetValues } from "../src/lib/schedule.ts";
import { fetchScheduleSheetValues } from "./schedule-sheet.mjs";

const OUTPUT_FILE = "src/data/generated/schedule.ts";
const ASSET_EXTENSIONS = new Set([".jpg", ".jpeg", ".png", ".webp"]);

async function collectAssetKeys(dirs) {
	const keys = new Set();

	for (const dir of dirs) {
		if (!existsSync(dir)) continue;

		const entries = await readdir(dir, { withFileTypes: true });
		for (const entry of entries) {
			const path = `${dir}/${entry.name}`;
			if (entry.isDirectory()) {
				for (const key of await collectAssetKeys([path])) keys.add(key);
				continue;
			}

			const ext = extname(entry.name).toLowerCase();
			if (entry.isFile() && ASSET_EXTENSIONS.has(ext)) {
				keys.add(basename(entry.name, ext));
			}
		}
	}

	return keys;
}

const [values, imageKeys, avatarKeys] = await Promise.all([
	fetchScheduleSheetValues(),
	collectAssetKeys(["src/assets/schedule"]),
	collectAssetKeys(["src/assets/speakers", "src/assets/feature-members"])
]);
const schedule = parseScheduleSheetValues(values, { imageKeys, avatarKeys });
const source = [
	"// This file is generated by `pnpm schedule:generate`. Do not edit manually.",
	'import type { ScheduleData } from "../../lib/schedule";',
	"",
	`export const scheduleData = ${JSON.stringify(schedule, null, "\t")} satisfies ScheduleData;`,
	""
].join("\n");

await mkdir(dirname(OUTPUT_FILE), { recursive: true });
const prettierOptions = (await resolveConfig(OUTPUT_FILE)) ?? {};
await writeFile(OUTPUT_FILE, await format(source, { ...prettierOptions, filepath: OUTPUT_FILE }));

console.log(`✓ Generated ${OUTPUT_FILE}: ${schedule.sessions.length} sessions, ${schedule.speakers.length} speakers, ${schedule.session_types.length} session types`);
